CREATE TABLE __SCHEMA__.objects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(255) NOT NULL,
    site_id BIGINT NOT NULL DEFAULT 0,
    created_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    creator_id BIGINT NOT NULL,
    asset_title VARCHAR(255) DEFAULT NULL,
    asset_mime_type VARCHAR(127) DEFAULT NULL,
    asset_original_name VARCHAR(255) DEFAULT NULL,
    asset_storage_key VARCHAR(128) DEFAULT NULL,
    asset_external_uri TEXT DEFAULT NULL,
    asset_size BIGINT DEFAULT NULL,
    asset_checksum VARCHAR(64) DEFAULT NULL,
    asset_public_token VARCHAR(64) DEFAULT NULL,
    asset_visibility VARCHAR(16) DEFAULT 'private',
    asset_processing_status VARCHAR(16) DEFAULT 'pending',
    token VARCHAR(255) DEFAULT NULL,
    expires_at TIMESTAMP(0) WITHOUT TIME ZONE DEFAULT NULL,
    api_token_user_id BIGINT DEFAULT NULL,
    slug VARCHAR(64) DEFAULT NULL,
    name VARCHAR(128) DEFAULT NULL,
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE DEFAULT NULL,
    icon_set_id BIGINT DEFAULT NULL,
    icon_name VARCHAR(64) DEFAULT NULL,
    svg TEXT DEFAULT NULL,
    CONSTRAINT fk_adc517d448d16f3b FOREIGN KEY (icon_set_id) REFERENCES __SCHEMA__.objects(id) ON DELETE CASCADE,
    CONSTRAINT fk_adc517d4e10c7f9a FOREIGN KEY (api_token_user_id) REFERENCES __SCHEMA__.objects(id),
    CONSTRAINT chk_digital_asset_required_fields CHECK (
        type NOT IN ('uploadeddigitalasset', 'externaldigitalasset')
        OR (asset_title IS NOT NULL AND asset_mime_type IS NOT NULL AND asset_public_token IS NOT NULL AND asset_visibility IS NOT NULL AND asset_processing_status IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uniq_api_token_token ON __SCHEMA__.objects (token);
CREATE UNIQUE INDEX uniq_object_icon_set_slug ON __SCHEMA__.objects (slug);
CREATE UNIQUE INDEX uniq_object_icon_set_name ON __SCHEMA__.objects (icon_set_id, icon_name);
CREATE UNIQUE INDEX uniq_asset_public_token ON __SCHEMA__.objects (asset_public_token);

CREATE TABLE __SCHEMA__.object_properties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    value JSONB DEFAULT NULL,
    secret BOOLEAN NOT NULL DEFAULT false
);
CREATE INDEX idx_object_property_object ON __SCHEMA__.object_properties (object_id);

CREATE TABLE __SCHEMA__.site_transfer_object_map (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_object_id BIGINT NOT NULL,
    destination_site_id BIGINT NOT NULL,
    CONSTRAINT fk_site_transfer_target_object FOREIGN KEY (destination_object_id) REFERENCES __SCHEMA__.objects(id) ON DELETE CASCADE,
    CONSTRAINT fk_site_transfer_target_site FOREIGN KEY (destination_site_id) REFERENCES __SCHEMA__.objects(id) ON DELETE CASCADE
);

CREATE TABLE __SCHEMA__.workflow_instance_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT DEFAULT NULL,
    CONSTRAINT fk_workflow_instance_event_actor FOREIGN KEY (actor_user_id) REFERENCES __SCHEMA__.objects(id) ON DELETE SET NULL
);

CREATE TABLE __SCHEMA__.workflow_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT DEFAULT NULL,
    CONSTRAINT fk_workflow_task_site FOREIGN KEY (site_id) REFERENCES __SCHEMA__.objects(id) ON DELETE RESTRICT
);

CREATE TABLE __SCHEMA__.object_reference (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id BIGINT NOT NULL REFERENCES __SCHEMA__.objects(id) ON DELETE CASCADE
);

