<?php

declare(strict_types=1);

namespace iikiti\CMS\Tests\Integration;

use Doctrine\DBAL\Connection;
use Doctrine\DBAL\Schema\Schema;
use DoctrineMigrations\Version20261114170000;
use Psr\Log\NullLogger;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;

final class ResponseHeadersPolicyMigrationTest extends KernelTestCase
{
	public function testMigratesSitePoliciesWithoutChangingExistingProperties(): void
	{
		self::bootKernel();
		$connection = self::getContainer()->get(Connection::class);
		$schemaName = 'headers_test_'.bin2hex(random_bytes(6));
		$schema = $connection->quoteSingleIdentifier($schemaName);
		$oldEnv = $_ENV['DB_SCHEMA'] ?? null;
		$oldServer = $_SERVER['DB_SCHEMA'] ?? null;
		$connection->beginTransaction();
		try {
			$connection->executeStatement("CREATE SCHEMA {$schema}");
			$connection->executeStatement("CREATE TABLE {$schema}.objects (id BIGINT PRIMARY KEY, type VARCHAR(255) NOT NULL)");
			$connection->executeStatement("CREATE TABLE {$schema}.object_properties (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, object_id BIGINT NOT NULL, name VARCHAR(255) NOT NULL, value JSON NOT NULL, secret BOOLEAN NOT NULL DEFAULT FALSE, created TIMESTAMP NOT NULL, creator_id BIGINT DEFAULT NULL)");
			$connection->executeStatement("INSERT INTO {$schema}.objects (id, type) VALUES (1, 'site'), (2, 'site'), (3, 'site'), (4, 'page'), (5, 'site'), (6, 'site'), (7, 'site')");
			$legacy = ['version' => 7, 'headers' => [
				['name' => 'Content-Security-Policy', 'mode' => 'default', 'value' => "default-src 'self' __IIKITI_CSP_NONCE__"],
				['name' => 'X-Frame-Options', 'mode' => 'off', 'value' => 'DENY'],
				['name' => 'Referrer-Policy', 'mode' => 'default', 'value' => ''],
				['name' => 'Unknown-Header', 'mode' => 'default', 'value' => 'ignored'],
			]];
			$existing = ['version' => 12, 'rules' => [['name' => 'X-Custom', 'action' => 'set', 'value' => 'kept', 'priority' => 0]]];
			foreach ([
				[1, 'security_headers_policy', $legacy],
				[1, 'configuration', ['security_headers_mode' => 'forced_off', 'other' => 'preserved']],
				[2, 'security_headers_policy', ['version' => 3, 'headers' => []]],
				[3, 'security_headers_policy', $legacy],
				[3, 'response_headers_policy', $existing],
				[4, 'security_headers_policy', $legacy],
				[6, 'security_headers_policy', ['version' => 4, 'headers' => [['name' => 'Unknown-Header', 'mode' => 'default', 'value' => 'ignored']]]],
				[7, 'security_headers_policy', ['version' => 5, 'headers' => [
					['name' => 'Content-Security-Policy-Report-Only', 'mode' => 'default', 'value' => "default-src 'none'"],
					['name' => 'Content-Security-Policy-Report-Only', 'mode' => 'off', 'value' => 'ignored'],
				]]],
			] as [$id, $name, $value]) {
				$connection->executeStatement("INSERT INTO {$schema}.object_properties (object_id, name, value, created) VALUES (?, ?, ?, CURRENT_TIMESTAMP)", [$id, $name, json_encode($value, JSON_THROW_ON_ERROR)]);
			}
			$_ENV['DB_SCHEMA'] = $_SERVER['DB_SCHEMA'] = $schemaName;
			require_once dirname(__DIR__, 2).'/migrations/Version20261114170000.php';
			for ($i = 0; $i < 2; ++$i) {
				$migration = new Version20261114170000($connection, new NullLogger());
				$migration->up(new Schema());
				foreach ($migration->getSql() as $query) {
					$connection->executeStatement($query->getStatement(), $query->getParameters(), $query->getTypes());
				}
			}
			$fetch = static function (int $id, string $name) use ($connection, $schema): mixed {
				$value = $connection->fetchOne("SELECT value FROM {$schema}.object_properties WHERE object_id = ? AND name = ?", [$id, $name]);

				return false === $value ? null : json_decode((string) $value, true, 512, JSON_THROW_ON_ERROR);
			};
			$policy = $fetch(1, 'response_headers_policy');
			self::assertSame(7, $policy['version']);
			$rules = array_column($policy['rules'], null, 'name');
			self::assertCount(9, $rules);
			self::assertSame(['name' => 'Content-Security-Policy', 'action' => 'set', 'value' => "default-src 'self' __IIKITI_CSP_NONCE__", 'priority' => 0], $rules['Content-Security-Policy']);
			foreach ($rules as $name => $rule) {
				if ('Content-Security-Policy' !== $name) {
					self::assertSame(['name' => $name, 'action' => 'remove', 'priority' => 0], $rule);
				}
			}
			self::assertSame(['version' => 3, 'rules' => []], $fetch(2, 'response_headers_policy'));
			self::assertSame($existing, $fetch(3, 'response_headers_policy'));
			self::assertNull($fetch(4, 'response_headers_policy'));
			self::assertNull($fetch(5, 'response_headers_policy'));
			$unknownOnly = $fetch(6, 'response_headers_policy');
			self::assertCount(9, $unknownOnly['rules']);
			self::assertSame(['remove'], array_values(array_unique(array_column($unknownOnly['rules'], 'action'))));
			$reportOnly = $fetch(7, 'response_headers_policy');
			self::assertSame(['name' => 'Content-Security-Policy-Report-Only', 'action' => 'set', 'value' => "default-src 'none'", 'priority' => 0], $reportOnly['rules'][0]);
			self::assertSame($legacy, $fetch(1, 'security_headers_policy'));
			self::assertSame(['security_headers_mode' => 'forced_off', 'other' => 'preserved'], $fetch(1, 'configuration'));
			self::assertSame(1, (int) $connection->fetchOne("SELECT COUNT(*) FROM {$schema}.object_properties WHERE object_id = 1 AND name = 'response_headers_policy'"));
			$connection->executeStatement("INSERT INTO {$schema}.objects (id, type) VALUES (8, 'site')");
			$invalid = ['version' => 1, 'headers' => [['name' => 'X-Frame-Options', 'mode' => 'on', 'value' => "DENY\r\nInjected: value"]]];
			$connection->executeStatement("INSERT INTO {$schema}.object_properties (object_id, name, value, created) VALUES (8, 'security_headers_policy', ?, CURRENT_TIMESTAMP)", [json_encode($invalid, JSON_THROW_ON_ERROR)]);
			try {
				(new Version20261114170000($connection, new NullLogger()))->up(new Schema());
				self::fail('Invalid legacy policy should stop migration.');
			} catch (\UnexpectedValueException $exception) {
				self::assertStringContainsString('site 8', $exception->getMessage());
			}
		} finally {
			$connection->rollBack();
			if (null === $oldEnv) {
				unset($_ENV['DB_SCHEMA']);
			} else {
				$_ENV['DB_SCHEMA'] = $oldEnv;
			}
			if (null === $oldServer) {
				unset($_SERVER['DB_SCHEMA']);
			} else {
				$_SERVER['DB_SCHEMA'] = $oldServer;
			}
		}
	}
}
